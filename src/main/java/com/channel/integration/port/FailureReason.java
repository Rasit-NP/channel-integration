package com.channel.integration.port;

/**
 * 공급사 조회 실패 사유.
 *
 * <p>공급사마다 실패를 알리는 방식이 다르다. 어떤 곳은 HTTP 상태 코드로, 어떤 곳은 항상 200 을
 * 주면서 응답 본문의 코드로만 알린다. 그 차이는 어댑터 안에서 흡수하고, 바깥에는 이 사유만
 * 노출한다. 도메인은 어느 공급사가 어떤 방식을 쓰는지 알지 못한다.
 *
 * <p>이 값은 그대로 응답의 실패 사유로 나가고, 나중에 공급사별 지표의 축으로도 쓴다.
 */
public enum FailureReason {

    /** 응답이 제때 오지 않음(연결·응답 타임아웃). */
    TIMEOUT,

    /** 공급사가 자기 쪽 오류를 알림(내부 오류·일시적 장애 등). */
    SUPPLIER_ERROR,

    /** 인증 실패. 키 설정 문제이므로 재시도해도 소용없다. */
    UNAUTHORIZED,

    /** 호출 한도 초과. 잠시 뒤 재시도할 여지가 있다. */
    RATE_LIMITED,

    /** 우리가 잘못 보냄(파라미터 오류, 묶음 크기 초과 등). 재시도 대상이 아니다. */
    INVALID_REQUEST,

    /** 응답은 왔으나 표준 모델로 변환할 수 없음. */
    MALFORMED_RESPONSE,

    /** 위 어디에도 넣기 어려운 경우. */
    UNKNOWN
}
